import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = resolve(root, 'test-results')
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const watchdog = setTimeout(() => browser.close(), 60000)
const errors = [], checks = []
try {
  const page = await browser.newPage({ viewport: { width: 1520, height: 1000 }, acceptDownloads: true })
  page.setDefaultTimeout(8000)
  page.on('pageerror', error => errors.push(error.message))
  await page.route(/^https?:/, route => { errors.push(`Unexpected network: ${route.request().url()}`); route.abort() })
  await page.goto(pathToFileURL(resolve(root, 'index.html')).href)
  const grid = page.locator('[data-grid-id="shared-grid-demo"]')
  await grid.getByText('示例任务 A', { exact: true }).waitFor()
  assert.equal(await grid.locator('tbody tr[data-row-index]').count(), 12)
  const style = await grid.locator('th').first().evaluate(el => { const s = getComputedStyle(el); return { background: s.backgroundColor, fontSize: s.fontSize } })
  assert.equal(style.background, 'rgb(238, 230, 220)')
  assert.equal(style.fontSize, '13px')
  checks.push('file:// 离线入口及原有表头配色/字号')
  await grid.getByText('示例任务 A', { exact: true }).dblclick()
  assert.match(await page.locator('.demo-bottom').innerText(), /打开 示例任务 A/)
  await grid.getByText('示例任务 B', { exact: true }).click({ button: 'right' })
  const menu = page.getByRole('menu')
  assert.equal(await menu.getByRole('menuitem').first().innerText(), '查看对应记录')
  await menu.getByRole('menuitem').first().click()
  assert.match(await page.locator('.demo-bottom').innerText(), /打开 示例任务 B/)
  checks.push('双击和右键首项共用动作')
  await grid.getByText('示例任务 A', { exact: true }).click()
  await grid.getByText('示例任务 C', { exact: true }).click({ modifiers: ['Shift'] })
  assert.equal(await page.locator('.demo-selection').innerText(), '已选择 3 条')
  await grid.getByText('示例任务 D', { exact: true }).click({ modifiers: ['Control'] })
  assert.equal(await page.locator('.demo-selection').innerText(), '已选择 4 条')
  checks.push('Shift 连选与 Ctrl 多选')
  await grid.getByText('示例任务 B', { exact: true }).click({ button: 'right' })
  await page.getByRole('menuitem', { name: '复制全部信息（4 行）', exact: true }).click()
  await page.getByText('已复制选中行', { exact: true }).waitFor()
  checks.push('浏览器实际复制选中行')
  const firstCell = await grid.getByText('示例任务 A', { exact: true }).boundingBox()
  const thirdCell = await grid.getByText('示例任务 C', { exact: true }).boundingBox()
  await page.mouse.move(firstCell.x + 12, firstCell.y + firstCell.height / 2)
  await page.mouse.down()
  await page.mouse.move(thirdCell.x + thirdCell.width - 12, thirdCell.y + thirdCell.height / 2, { steps: 12 })
  await page.mouse.up()
  assert.equal(await page.locator('.demo-selection').innerText(), '已选择 3 条')
  checks.push('鼠标拖拽框选')
  await grid.getByRole('button', { name: '进度', exact: true }).click()
  const values = await grid.locator('tbody tr[data-row-index] td:nth-child(6)').allTextContents()
  assert.deepEqual(values.map(parseFloat), [...values.map(parseFloat)].sort((a, b) => a - b))
  await grid.getByRole('button', { name: '序号', exact: true }).click()
  await grid.getByRole('button', { name: '添加筛选' }).click()
  const filter = page.getByRole('dialog', { name: '添加筛选条件' })
  await filter.getByLabel('字段', { exact: true }).selectOption('category')
  await filter.getByLabel('值', { exact: true }).selectOption('内容审核')
  await filter.getByRole('button', { name: '应用' }).click()
  assert.equal(await grid.locator('tbody tr[data-row-index]').count(), 4)
  checks.push('排序、恢复顺序与枚举筛选')
  const downloadPromise = page.waitForEvent('download')
  await grid.getByRole('button', { name: '导出全部' }).click()
  const download = await downloadPromise
  const downloadPath = resolve(output, 'export.csv'); await download.saveAs(downloadPath)
  assert.equal(readFileSync(downloadPath, 'utf8').split('\r\n').length, 13)
  checks.push('筛选后导出仍包含全部 12 条')
  await grid.getByRole('button', { name: '清除筛选', exact: true }).click()
  const resize = grid.getByRole('button', { name: '调整任务名称列宽', exact: true })
  const before = await grid.locator('col[data-column-key="name"]').evaluate(el => parseFloat(el.style.width))
  await resize.focus(); await page.keyboard.press('ArrowRight')
  assert.equal(await grid.locator('col[data-column-key="name"]').evaluate(el => parseFloat(el.style.width)), before + 8)
  await page.reload(); await grid.waitFor()
  assert.equal(await grid.locator('col[data-column-key="name"]').evaluate(el => parseFloat(el.style.width)), before + 8)
  await page.getByRole('button', { name: '重置列布局' }).click()
  checks.push('列宽调整、刷新持久化与重置')
  await grid.locator('th').filter({ has: page.getByRole('button', { name: '负责人', exact: true }) }).locator('.column-heading').dragTo(grid.locator('th').filter({ has: page.getByRole('button', { name: '类型', exact: true }) }).locator('.column-heading'))
  const order = await grid.locator('col').evaluateAll(els => els.map(el => el.dataset.columnKey))
  assert.ok(order.indexOf('owner') < order.indexOf('category'))
  await page.reload(); await grid.waitFor()
  assert.deepEqual(await grid.locator('col').evaluateAll(els => els.map(el => el.dataset.columnKey)), order)
  await page.getByRole('button', { name: '重置列布局' }).click()
  checks.push('拖动换列并刷新保持顺序')
  await page.getByRole('button', { name: '加载 300 条' }).click()
  for (const scale of [1, 1.4]) {
    await page.evaluate(scale => { document.documentElement.style.zoom = scale }, scale)
    await grid.getByRole('button', { name: '清空', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '清空全部数据', exact: true })
    const box = await dialog.boundingBox(), viewport = page.viewportSize()
    assert.ok(Math.abs(box.x + box.width / 2 - viewport.width / 2) < 3)
    assert.ok(Math.abs(box.y + box.height / 2 - viewport.height / 2) < 3)
    assert.ok(box.y >= 0 && box.y + box.height <= viewport.height)
    await dialog.getByRole('button', { name: '取消' }).click()
  }
  await page.evaluate(() => { document.documentElement.style.zoom = 1 })
  checks.push('300 行长表格及 100% / 140% 缩放下清空弹窗居中')
  await page.getByRole('button', { name: '恢复示例数据' }).click()
  await page.locator('summary').click()
  await page.getByRole('checkbox', { name: /模拟清空失败/ }).check()
  await grid.getByRole('button', { name: '清空', exact: true }).click()
  await page.getByRole('button', { name: '确认清空' }).click()
  await page.getByRole('alert').waitFor()
  assert.equal(await grid.locator('tbody tr[data-row-index]').count(), 12)
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('checkbox', { name: /模拟清空失败/ }).uncheck()
  await grid.getByRole('button', { name: '清空', exact: true }).click()
  await page.getByRole('button', { name: '确认清空' }).click()
  await grid.getByText('暂无数据', { exact: true }).waitFor()
  checks.push('清空失败保留数据、确认清空及空状态')
  await page.getByRole('button', { name: '恢复示例数据' }).click()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: resolve(output, 'gallery.png'), fullPage: true })
  await page.setViewportSize({ width: 480, height: 800 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await grid.getByRole('button', { name: '添加筛选' }).click()
  const narrow = await filter.boundingBox()
  assert.ok(narrow.x >= 0 && narrow.x + narrow.width <= 480)
  await filter.getByRole('button', { name: '取消' }).click()
  await page.goto(pathToFileURL(resolve(root, 'yuntu_grid/demo/index.html')).href)
  await page.getByText('示例任务 A', { exact: true }).waitFor()
  checks.push('窄屏可横向滚动表格、独立演示离线打开')
  assert.deepEqual(errors, [])
  writeFileSync(resolve(output, 'ui-report.json'), JSON.stringify({ checks, errors }, null, 2))
  console.log(JSON.stringify({ passed: checks.length, checks }, null, 2))
} finally { clearTimeout(watchdog); await browser.close() }
